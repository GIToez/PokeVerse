return function(t, H)
  H.setup()
  H.call('Charizard')
  H.zoom(-1)
  H.flyover('c_fly_kanto', '3289,837,7', 'moltres', { { 'n', 2500 }, { 'ne', 3000 } })
  H.flyover('c_fly_johto', '2314,730,7', 'ho-oh', { { 'e', 3000 }, { 'ne', 2500 } })
  H.flyover('c_fly_orange', '3521,1937,7', 'lugia', { { 'w', 3000 }, { 'sw', 2500 } })
  H.flyover('c_fly_hoenn', '1407,1348,7', 'rayquaza', { { 'nw', 3000 }, { 'n', 2500 } })
  H.zoom(1)
  -- surf Pikachu at Pallet
  H.go('3297,848,7')
  H.call('Pikachu')
  H.say('/itch surfboard', 1500)
  H.wait(1500)
  H.walk(0, 1, 300)
  H.wait(1200)
  H.rec('c_surf')
  H.order(0, 1, 400)
  H.wait(2500)
  H.steer('s', 3500)
  H.steer('e', 3000)
  H.stop()
  -- ride Arcanine down Route 1, then Warp Spin out
  H.go('3291,713,7')
  H.call('Arcanine')
  H.wait(800)
  H.rec('c_ride')
  H.order(0, 0, 400)
  H.wait(2000)
  H.steer('n', 4000)
  H.say('/warpstyle spin teleport', 300)
  H.wait(2500)
  H.stop()
  H.order(0, 0, 400)
  -- Warp Styles in Viridian
  H.go('3305,557,7')
  H.wait(1500)
  H.rec('c_warps')
  H.say('/warpstyle pokeball teleport', 300)
  H.wait(2800)
  H.say('/warpstyle beam teleport', 300)
  H.wait(2800)
  H.say('/warpstyle fireworks victory', 300)
  H.wait(3000)
  H.stop()
end
