return function(t, H)
  H.setup()
  H.say('/legendary end groudon', 300)
  -- hook: Route 2, Mega Charizard X against a wild Venusaur, then the catch
  H.go('3302,433,7')
  H.wait(1500)
  H.rec('a_hook')
  H.walk(0, -6, 200)
  H.wait(2500)
  H.call('Charizard', 1800)
  H.say('/mega full', 600)
  H.say('/mega x', 1500)
  H.wait(5500)
  H.say('/m Venusaur', 300)
  H.attackNearest(800)
  H.moves({ 'm1', 'm2', 'm3', 'm4', 'm5' }, 900)
  H.say('/itch weaken 95', 200)
  H.attackName('Venusaur', 200)
  H.moves({ 'm6', 'm7', 'm1', 'm2' }, 900)
  H.wait(1500)
  H.stopFight()
  H.say('/itch catch ultra venusaur', 600)
  H.wait(6000)
  H.stop()
  H.say('/mega off', 500)
  -- legendary: Groudon at Lilycove
  H.go('1407,1348,7')
  H.call('Blastoise')
  H.wait(1500)
  H.rec('a_groudon')
  H.say('/legendary spawn groudon here', 300)
  H.wait(3000)
  H.say('/itch noflee', 300)
  H.wait(1500)
  H.attackName('Groudon', 300)
  H.moves({ 'm1', 'm2', 'm3', 'm4', 'm5', 'm6', 'm7', 'm8' }, 900)
  H.say('/itch weaken 90', 300)
  H.attackName('Groudon', 300)
  H.moves({ 'm1', 'm2', 'm3', 'm4' }, 900)
  H.say('/itch weaken 95', 300)
  H.attackName('Groudon', 300)
  H.moves({ 'm5', 'm6', 'm1', 'm2', 'm3' }, 900)
  H.wait(1500)
  H.stopFight()
  H.say('/itch catch master groudon', 600)
  H.wait(7000)
  H.shot('a_groudon_caught')
  H.stop()
end
