return function(t, H)
  H.setup()
  H.say('/legendary end groudon', 300)
  -- legendary: Groudon at Lilycove
  H.go('1407,1348,7')
  H.call('Blastoise')
  H.wait(1500)
  H.rec('a_groudon')
