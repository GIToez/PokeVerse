  H.wait(3000)
  H.say('/itch noflee', 300)
  H.wait(1500)
  H.attackName('Groudon', 300)
  H.moves({ 'm1', 'm2', 'm3', 'm4', 'm5', 'm6', 'm7', 'm8' }, 900)
  H.say('/legendary health groudon 30', 300)
  H.attackName('Groudon', 300)
  H.moves({ 'm1', 'm2', 'm3', 'm4' }, 900)
  H.say('/itch hp 2500', 300)
  H.attackName('Groudon', 300)
  H.moves({ 'm5', 'm6', 'm1', 'm2', 'm3' }, 900)
