return function(t, H)
  H.setup()
  -- ride Arcanine through Goldenrod
  H.go('2314,730,7')
  H.call('Arcanine')
  H.wait(800)
  H.rec('d_ride')
  H.order(0, 0, 400)
  H.wait(1800)
  H.steer('e', 3500)
  H.steer('ne', 1500)
  H.stop()
  H.order(0, 0, 400)
  -- a thunderstorm rolls in, then night falls
  H.go('3289,837,7')
  H.call('Venusaur')
  H.rec('d_storm')
  H.say('/weather here thunderstorm', 1500)
  H.wait(6000)
  H.stop()
  H.rec('d_night')
  H.say('/weather time dusk', 1500)
  H.say('/weather time night', 2500)
  H.wait(3000)
  H.stop()
  H.say('/weather here clear', 500)
  H.say('/weather time day', 300)
  -- menus: quest log with View on map, Trainer Card, vocation window
  H.go('3700,455,7')
  H.call('Charizard')
  H.rec('d_ui')
  H.add(2800, function() modules.game_quests.openTab('available') end)
  H.add(3000, function() local b = t.child('viewMap') if b and b.onClick then b.onClick(b) end end)
  H.add(600, function() pcall(function() modules.game_pokepedia.hide() end) end)
  H.add(3000, function() modules.game_trainercard.toggle() end)
  H.add(600, function() pcall(function() modules.game_trainercard.close() end) end)
  H.say('/vocation', 2800)
  H.closeAll()
  H.stop()
  H.say('/weather all auto', 500)
end
