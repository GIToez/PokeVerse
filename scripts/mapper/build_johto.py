class Field:
    """Arrays over a box (BOX by default), indexed [y - y0, x - x0]."""

    def __init__(self, seed, box=BOX):
        self.x0, self.y0, self.x1, self.y1 = box
        self.w, self.h = self.x1 - self.x0 + 1, self.y1 - self.y0 + 1
        self.rng = np.random.default_rng(seed)
        yy, xx = np.mgrid[0:self.h, 0:self.w]
        self.X, self.Y = xx + self.x0, yy + self.y0

    def noise(self, scale, octaves=3):
        out = np.zeros((self.h, self.w))
        amp, tot = 1.0, 0.0
        for o in range(octaves):
            s = max(2, int(scale / (2 ** o)))
            g = self.rng.random((self.h // s + 3, self.w // s + 3)).astype(np.float32)
            img = Image.fromarray(g, 'F').resize(((self.w // s + 3) * s, (self.h // s + 3) * s), Image.BICUBIC)
            out += amp * (np.asarray(img)[:self.h, :self.w] - 0.5)
            tot += amp
            amp *= 0.5
        return out / tot

    def refine(self, coarse, n, amp=0.35):
        """Coarse layout mask -> tile mask, with a soft, noisy edge."""
        lx0, ly0 = L.LAYOUT_BOX[:2]
        C = L.CELL
        img = Image.fromarray(coarse.astype(np.float32), 'F')
        up = np.asarray(img.resize((coarse.shape[1] * C, coarse.shape[0] * C), Image.BILINEAR))
        oy, ox = self.y0 - ly0 - C // 2, self.x0 - lx0 - C // 2
        crop = up[oy:oy + self.h, ox:ox + self.w]
        return crop + n * amp > 0.5

    def seg_dist(self, pts):
        d = np.full((self.h, self.w), 1e9)
        for (ax, ay), (bx, by) in zip(pts, pts[1:]):
            vx, vy = bx - ax, by - ay
            t = np.clip(((self.X - ax) * vx + (self.Y - ay) * vy) / max(1, vx * vx + vy * vy), 0, 1)
            d = np.minimum(d, np.hypot(self.X - (ax + t * vx), self.Y - (ay + t * vy)))
        return d

    def disc(self, cx, cy, r, n=None, amp=0.0):
        d = np.hypot(self.X - cx, self.Y - cy) / r
        if n is not None:
            d = d + n * amp
        return d < 1.0


def dilate(mask, size):
    img = Image.fromarray(mask.astype(np.uint8) * 255)
    return np.asarray(img.filter(ImageFilter.MaxFilter(size))) > 0


def erode(mask, size):
    img = Image.fromarray(mask.astype(np.uint8) * 255)
    return np.asarray(img.filter(ImageFilter.MinFilter(size))) > 0


def smooth_path(pts, rng, wobble=10, step=12):
    """Polyline with gentle bends so roads do not look ruler-drawn."""
    out = [pts[0]]
    for (ax, ay), (bx, by) in zip(pts, pts[1:]):
        n = max(1, int(np.hypot(bx - ax, by - ay) / step))
        nx, ny = -(by - ay), bx - ax
        ln = max(1.0, np.hypot(nx, ny))
        phase = rng.random() * 6.28
        for i in range(1, n + 1):
            t = i / n
            off = 0 if i == n else np.sin(t * 3.14 * 1.5 + phase) * wobble * np.sin(t * 3.14)
            out.append((ax + (bx - ax) * t + nx / ln * off, ay + (by - ay) * t + ny / ln * off))
    return out


