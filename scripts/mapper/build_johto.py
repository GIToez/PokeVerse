def pick(rng, table):
    ids, weights = zip(*table)
    w = np.array(weights, float)
    return ids[rng.choice(len(ids), p=w / w.sum())]


def build_cave(brushes, present, rng):
    """Mt. Silver Cave 1F, made like Kanto's caves: mountain top ground carved out of solid mountain,
    patches of rocky ground, debris and stones on the floor and candles on the walls."""
    z = CAVE['z']
    f = Field(41, CAVE['box'])
    X, Y = f.X, f.Y
    n1, n2 = f.noise(8), f.noise(16)
    ex, ey = MT_SILVER['cave']
    path_d = f.seg_dist(smooth_path(CAVE['path'], rng, 4, 8))
    # at least 5 wide everywhere, so 3 tiles stay walkable between the wall borders
    floor = (path_d + n1 * 3 < 2.6) | (path_d < 2.5)
    for x, y, r in CAVE['rooms']:
        floor |= f.disc(x, y, r, n2, 0.5)
    floor |= (abs(X - ex) <= 2) & (Y >= ey - 5) & (Y <= ey + 1)
    floor &= Y <= ey + 1
    water = f.disc(*CAVE['pond'], n1, 0.3) & erode(floor, 3)
    rocky = (f.noise(10) > 0.2) & erode(floor, 3) & ~water
    wall = dilate(floor, 7) & ~floor
    bx0, by0 = BOX[:2]
    occupied = present[f.y0 - by0:f.y1 - by0 + 1, f.x0 - bx0:f.x1 - bx0 + 1]
    assert not (occupied & (floor | wall)).any(), 'Mt. Silver Cave overlaps existing tiles'

    names = np.full((f.h, f.w), '', object)
    names[wall] = 'mountain'
    names[floor] = 'mountain top ground'
    names[rocky] = 'rocky ground'
    names[water] = 'walkable sea'
    near_stairs = (abs(X - ex) <= 3) & (abs(Y - ey) <= 4)
    shore = dilate(water, 5)
    inner = erode(floor, 5)  # the optional mountain border on the tiles along the walls blocks
    ground = {}
    deco = {}
    walk = np.zeros((f.h, f.w), bool)
    for iy, ix in np.argwhere(names != ''):
        x, y = ix + f.x0, iy + f.y0
        brush = brushes[names[iy, ix]]
        ground[(x, y)] = pick(rng, [(i, c) for i, c in brush.items if c > 0])
        items = []
        r = rng.random()
        if wall[iy, ix]:
            if iy + 1 < f.h and floor[iy + 1, ix] and not water[iy + 1, ix] and r < 0.05:
                items.append(WALL_CANDLE)
        elif not water[iy, ix] and not near_stairs[iy, ix]:
            if r < 0.06:
                items.append(int(rng.choice(CAVE_DEBRIS)))
            elif r < 0.085:
                items.append(int(rng.choice(CAVE_STONES)))
            elif not shore[iy, ix] and inner[iy, ix]:
                walk[iy, ix] = True
        deco[(x, y)] = items
    deco[(ex, ey - 1)] = [STAIRS_UP]

    def brush_at(x, y):
        g = ground.get((x, y))
        return brushes.by_item.get(g) if g is not None else None

    mountain = brushes['mountain']
    tiles = {}
    for (x, y), g in ground.items():
        center = brushes.by_item.get(g)
        nb = [brush_at(x + dx, y + dy) for dx, dy in autoborder.NEIGHBOURS]
        optional = center is not mountain and mountain in nb and not (abs(x - ex) <= 1 and ey - 2 <= y <= ey)
        border = brushes.borders_for(center, nb, optional=optional)
        children = b''.join(pvmap.item_node(i) for i in [g] + border + deco[(x, y)])
        tiles[(x, y, z)] = pvmap.RawTile(0, 0, None, children)

    spawns = []
    for iy, ix in np.argwhere(walk & (rng.random((f.h, f.w)) < 1 / 70.0)):
        spawns.append((pick(rng, spawn_table('Mt. Silver Cave')), ix + f.x0, iy + f.y0, z))
    return tiles, spawns, []


def build(base, out_path):
    brushes = autoborder.Brushes()
    scanned = scan(base)
    keep = scanned['keep']
    present = scanned['present'][1:-1, 1:-1]
    coarse = L.concept(ground_class(scanned['ground7'], brushes), scanned['occupied'])
    f = Field(29)
    rng = np.random.default_rng(29)
    X, Y = f.X, f.Y

    nature = set(brushes.by_item) | brushes.border_item_ids
    for table in (BIG_TREES, BUSHES, TUFTS, FERNS, FLOWERS, STONES):
        nature.update(i for i, _ in table)
    nature.update(GRAVEL)
    nature.update(range(6476, 6489))

    def existing(x, y):
        return keep.get((x, y, Z))

    def existing_ids(x, y):
        t = existing(x, y)
        if t is None:
            return None
        return ([t.ground] if t.ground is not None else []) + pvmap.child_item_ids(t.children)

    # Which tiles this pass may write.
    kx0, ky0, kx1, ky1 = KANTO_EDIT
    editable = np.zeros((f.h, f.w), bool)
    for y in range(ky0, ky1 + 1):
        for x in range(kx0, kx1 + 1):
            ids = existing_ids(x, y)
            if ids and len(ids) == 1 and brushes.by_item.get(ids[0]) is brushes['grass']:
                editable[y - f.y0, x - f.x0] = True
    n1, n2, n3 = f.noise(14), f.noise(10), f.noise(24)
    # The west gate's pass: Kanto's mountain (and plain nature) along PASS_LINE is redone.
    pass_d = f.seg_dist(PASS_LINE)
    pass_edit = np.zeros((f.h, f.w), bool)
    px0, py0, px1, py1 = PASS_BOX
    for y in range(py0, py1 + 1):
        for x in range(px0, px1 + 1):
            ids = existing_ids(x, y)
            iy, ix = y - f.y0, x - f.x0
            if ids and all(i in nature or i in PASS_CLEAR for i in ids) and pass_d[iy, ix] + n2[iy, ix] * 3 < 4.5:
                pass_edit[iy, ix] = True
    editable |= pass_edit
    edge = f.noise(30)
    outline = (X > NORTH[0] + 25 + edge * 40) & (Y > f.y0 + 25 + edge * 40)
    north_scope = (X >= NORTH[0]) & (X <= NORTH[1]) & outline
    scope = (Y >= 600) | north_scope | pass_edit
    gen = (~present | editable) & scope

    # Terrain from the layout, refined to tiles.
    land = f.refine(coarse['land'], n1)
    mount = f.refine(coarse['mount'], n2, 0.45) & land
    forest = f.refine(coarse['forest'], n3, 0.5) & land
    water = f.refine(coarse['lakes'], n2) & land

    # The Kanto strip: carry the existing ground across the seam.
    for y in range(f.y0, f.y1 + 1):
        ids = existing_ids(3050, y)
        if not ids:
            continue
        b = brushes.by_item.get(ids[0])
        strip = (Y == y) & (X < 3050)
        if b is brushes['mountain']:
            sel = strip & (X >= 3020 + (n1 * 18).astype(int))
            land |= sel
            mount |= sel
        elif b is brushes['grass']:
            sel = strip & (X >= 3005 + (n1 * 20).astype(int))
            land |= sel
            mount &= ~(sel & (X >= 3030))
        elif ids[0] in WATER_IDS:
            sel = strip & (X >= 3030 + (n1 * 20).astype(int))
            land &= ~sel
    land |= editable
    # North of the ridge everything is the Silver-Indigo range, up to the plateau's west edge, except
    # the Route 28 valley that runs from the west gate to the clearing at the foot of Mt. Silver.
    upper = ((Y < 640 + n2 * 10) & (X > 2780) & (X < 3050)) | ((Y < 612) & north_scope & ~present)
    bx, by, br = MT_SILVER['base']
    silver_base = f.disc(bx, by, br, f.noise(12), 0.4)
    valley = (f.seg_dist(ROUTE_28) + n2 * 10 < 12) | f.disc(2975, 598, 13, n1, 0.4) | silver_base
    valley &= upper & (X < 3050)
    pond = f.disc(2972, 601, 4.5, n1, 0.3) & valley
    # Mountain wall between Route 26 and Route 28, joining Kanto's ridge west of the plateau.
    ridge_line = [(2800, 655), (2870, 645), (2940, 652), (3000, 640), (3049, 628)]
    ridge = ((f.seg_dist(ridge_line) + n2 * 14 < 16) & (X > 2780) & (X < 3050)) | (upper & ~valley)
    land |= ridge & (X > 2790)
    land |= valley
    water &= ~upper
    water |= pond
    forest &= ~upper
    mount |= ridge & land
    mount &= ~valley
    snow_peak = f.disc(2905, 400, 75, n3, 0.6) & (f.noise(14) > 0.04) & erode(mount & upper, 9)
    # Tohjo Falls: the river comes out of the ridge.
    falls = (2905, 668)
    mount |= f.disc(falls[0], falls[1] - 4, 13, n2, 0.4) & land
    river_line = smooth_path([(2905, 660), (2903, 690), (2908, 712), (2915, 760), (2925, 820), (2935, 860)], rng, 5, 10)
    river = f.seg_dist(river_line) + n2 * 3 < 3.2
    water |= river & land & (Y >= 668)
    mount &= ~(river & (Y >= 668))

    # Roads.
    road_pts = {
        '26': smooth_path([(3049, 700), (3010, 701), (2965, 706), (2920, 712), (2895, 714)], rng, 6),
        '27': smooth_path([(2895, 714), (2860, 745), (2815, 772), (2760, 793), (2735, 800)], rng, 8),
        '29': smooth_path([(2705, 800), (2660, 822), (2610, 832), (2560, 836), (2520, 838)], rng, 8),
        'gate': smooth_path([(3049, 700), (3066, 676), (3080, 650), (3094, 628), (3105, 614)], rng, 4),
        'town': [(2735, 800), (2705, 800)],
        'pass': PASS_LINE,
        '28': smooth_path(ROUTE_28, rng, 5),
        'silver': [ROUTE_28[-1], (2906, 516), (MT_SILVER['cave'][0], MT_SILVER['cave'][1] + 2)],
        'pokecenter': [ROUTE_28[-1], (MT_SILVER['pokecenter'][0] + 4, ROUTE_28[-1][1])],
    }
    road_d = np.full((f.h, f.w), 1e9)
    for pts in road_pts.values():
        road_d = np.minimum(road_d, f.seg_dist(pts))
    nroad = f.noise(6)
    road = road_d + nroad * 2.5 < 2.0
    mount &= ~(road_d < 6 + n2 * 4)
    forest &= ~(road_d < 4)
    land |= road & ~water

    # New Bark Town.
    tx, ty = NEW_BARK['temple']
    town = f.disc(2718, 800, 40, f.noise(12), 0.5)
    mount &= ~town
    forest &= ~f.disc(2718, 800, 46, f.noise(12), 0.5)
    water &= ~town
    land |= town

    terrain = np.zeros((f.h, f.w), np.uint8)
    terrain[land] = GRASS
    terrain[~land] = WATER
    lawn = (f.noise(30, 4) > 0.2) & land
    dirt = (f.noise(40, 4) > 0.24) & land
    terrain[lawn & ~pass_edit] = LAWN
    terrain[dirt] = DIRT
    coast = land & dilate(~land, 7) & (Y > 845) & (f.noise(20) > -0.12)
    terrain[coast] = SAND
    terrain[mount] = MOUNTAIN
    terrain[water] = WATER
    terrain[road & ~water] = DIRT
    terrain[snow_peak] = SNOW_PEAK
    clear = np.zeros((f.h, f.w), bool)
    # Mt. Silver's cave mouth: stairs down set one tile into the rock face, open to the south.
    cx, cy = MT_SILVER['cave']
    ix, iy = cx - f.x0, cy - f.y0
    terrain[f.disc(cx, cy - 5, 6.5, f.noise(4), 0.4) | f.disc(cx, cy - 1, 2.5)] = MOUNTAIN
    terrain[iy, ix] = STAIRS
    terrain[iy + 1:iy + 4, ix - 1:ix + 2] = DIRT
    clear[iy - 1:iy + 5, ix - 3:ix + 4] = True

    # Wooden bridge where Route 26 crosses the Tohjo river, built like Kanto's bridges.
    bridge = {}
    cols = [x for x in range(2885, 2935) if (terrain[:, x - f.x0] == WATER).any()]
    r0, r1 = 680 - f.y0, 740 - f.y0  # Route 26's crossing, not Route 28 further up the same columns
    for x in cols:
        ry = r0 + int(np.argmin(road_d[r0:r1, x - f.x0]))
        if road_d[ry, x - f.x0] < 2 and terrain[ry, x - f.x0] == WATER:
            for xx in (x - 1, x, x + 1):
                for k, yy in enumerate((ry - 1, ry, ry + 1)):
                    bridge[(xx, yy + f.y0)] = k
    for (x, y) in bridge:
        terrain[y - f.y0, x - f.x0] = BRIDGE

    # Prefabs.
    houses_xml = house_entries()
    next_house = max(houses_xml) + 1
    prefab_tiles = {}
    npcs = []
    new_houses = []
    prefabs = {name: Prefab(name, spec, keep, brushes, nature) for name, spec in PREFABS.items()}
    placements = [(name, ox, oy, NEW_BARK, 800) for name, ox, oy in NEW_BARK['buildings']]
    placements.append(('pokecenter',) + MT_SILVER['pokecenter'] + (MT_SILVER, None))
    for name, ox, oy, place, street in placements:
        p = prefabs[name]
        remap = {}
        for hid in sorted(p.house_ids):
            remap[hid] = next_house
            next_house += 1
        for (dx, dy, dz), tile in p.tiles.items():
            t = pvmap.RawTile(remap.get(tile.house_id, 0), tile.flags, tile.ground, tile.children)
            prefab_tiles[(ox + dx, oy + dy, Z + dz)] = t
        for hid, new_id in remap.items():
            src = houses_xml[hid]
            sx, sy = p.src
            size = sum(1 for t in p.tiles.values() if t.house_id == hid)
            n = sum(1 for h in new_houses if h['townid'] == place['town_id']) + 1
            new_houses.append({'name': '%s House #%d' % (place['name'], n), 'houseid': new_id,
                               'entryx': int(src['entryx']) - sx + ox, 'entryy': int(src['entryy']) - sy + oy,
                               'entryz': Z, 'rent': 0, 'townid': place['town_id'], 'size': size})
        for n, dx, dy in p.npcs:
            npcs.append((n, ox + dx, oy + dy, Z))
        y0, x0 = oy - f.y0, ox - f.x0
        clear[y0 - 2:y0 + p.h + 2, x0 - 2:x0 + p.w + 2] = True
        terrain[y0 - 1:y0 + p.h + 1, x0 - 1:x0 + p.w + 1] = GRASS
        # path from the front door to the main street, or a short apron for houses south of it
        door_x = x0 + p.w // 2
        if street is not None and oy + p.h <= street:
            end = street - f.y0 + 1
        else:
            end = y0 + p.h + 3
        terrain[y0 + p.h:end, door_x - 1:door_x + 1] = DIRT
        clear[y0 + p.h:end, door_x - 2:door_x + 2] = True
    # Town square in front of the Pokémon Center.
    sq = f.disc(tx, ty + 1, 5.5, f.noise(4), 0.3)
    terrain[sq & land] = DIRT
    clear |= sq | f.disc(tx, ty, 8)

    for (x, y, z) in prefab_tiles:
        if z == Z and f.x0 <= x <= f.x1 and f.y0 <= y <= f.y1:
            gen[y - f.y0, x - f.x0] = False

    # Existing spawns on Kanto tiles being redone must stay on walkable ground.
    keep_free = np.zeros((f.h, f.w), bool)
    src = open(os.path.join(WORLD, 'map-spawn.xml'), encoding='latin-1').read()
    for m in re.finditer(r'<spawn centerx="(\d+)" centery="(\d+)" centerz="(\d+)"[^>]*>(.*?)</spawn>', src, re.S):
        if int(m.group(3)) != Z:
            continue
        for c in re.finditer(r' x="(-?\d+)" y="(-?\d+)"', m.group(4)):
            x, y = int(m.group(1)) + int(c.group(1)), int(m.group(2)) + int(c.group(2))
            if f.x0 <= x <= f.x1 and f.y0 <= y <= f.y1:
                keep_free[y - f.y0, x - f.x0] = True

    # Ground items and decoration.
    groves = f.noise(20)
    tufty = f.noise(8)
    flowery = f.noise(10)
    tiles = {}
    blocked_spawn = np.zeros((f.h, f.w), bool)
    for iy in range(f.h):
        for ix in range(f.w):
            if not gen[iy, ix]:
                continue
            x, y = ix + f.x0, iy + f.y0
            cls = int(terrain[iy, ix])
            if cls == BRIDGE:
                plank, rails = BRIDGE_ROWS[bridge[(x, y)]]
                tiles[(x, y)] = [plank, list(rails[x % 2])]
                blocked_spawn[iy, ix] = True
                continue
            if cls == STAIRS:
                tiles[(x, y)] = [STAIRS_DOWN, []]
                blocked_spawn[iy, ix] = True
                continue
            brush = brushes[BRUSH_OF[cls]]
            ground = pick(rng, [(i, c) for i, c in brush.items if c > 0])
            deco = []
            r = rng.random()
            if cls in (GRASS, LAWN) and not clear[iy, ix] and not road[iy, ix]:
                g = groves[iy, ix]
                if keep_free[iy, ix]:
                    r = 1.0
                if forest[iy, ix]:
                    p_tree, p_bush = 0.45, 0.15
                else:
                    p_tree = 0.02 + 0.5 * max(0.0, g - 0.05)
                    p_bush = 0.03 + 0.35 * max(0.0, g + 0.05)
                if road_d[iy, ix] < 3.5:
                    p_tree *= 0.15
                    p_bush *= 0.3
                if r < p_tree:
                    deco.append(pick(rng, BIG_TREES))
                elif r < p_tree + p_bush:
                    deco.append(pick(rng, BUSHES))
                else:
                    r2 = rng.random()
                    p_tuft = 0.3 + 0.25 * tufty[iy, ix]
                    p_flower = 0.004 + 0.03 * max(0.0, flowery[iy, ix] - 0.15)
                    if keep_free[iy, ix]:
                        pass
                    elif r2 < p_tuft:
                        deco.append(pick(rng, TUFTS))
                    elif r2 < p_tuft + 0.03:
                        deco.append(pick(rng, FERNS))
                    elif r2 < p_tuft + 0.03 + p_flower:
                        deco.append(pick(rng, FLOWERS))
                    elif r2 < p_tuft + 0.036 + p_flower:
                        deco.append(pick(rng, STONES))
            elif cls == DIRT and not clear[iy, ix] and r < 0.18:
                deco.append(rng.choice(GRAVEL))
            if deco and deco[0] not in dict(TUFTS) and deco[0] not in dict(FERNS) and deco[0] not in dict(FLOWERS):
                blocked_spawn[iy, ix] = True
            tiles[(x, y)] = [ground, deco]

    # Borders.
    stair_landing = {(cx + dx, cy + dy) for dx in (-1, 0, 1) for dy in (1, 2, 3)}

    def brush_at(x, y):
        if (x, y) in tiles:
            return brushes.by_item.get(tiles[(x, y)][0])
        pt = prefab_tiles.get((x, y, Z))
        if pt is not None:
            ids = ([pt.ground] if pt.ground is not None else []) + pvmap.child_item_ids(pt.children)
            return brushes.by_item.get(ids[0]) if ids else None
        ids = existing_ids(x, y)
        return brushes.by_item.get(ids[0]) if ids else None

    mountain = brushes['mountain']
    new_tiles = {}
    for (x, y), (ground, deco) in tiles.items():
        center = brushes.by_item.get(ground)
        border = []
        if center is not None:
            nb = [brush_at(x + dx, y + dy) for dx, dy in autoborder.NEIGHBOURS]
            # the optional mountain border blocks, and players come up the cave stairs onto these tiles
            optional = center is not mountain and mountain in nb and (x, y) not in stair_landing
            border = brushes.borders_for(center, nb, optional=optional)
        children = b''.join(pvmap.item_node(i) for i in [ground] + border + deco)
        new_tiles[(x, y, Z)] = pvmap.RawTile(0, 0, None, children)
    # Kanto tiles touching the new ones get their borders redone; everything else on them stays.
    ring = set()
    for (x, y, _z) in list(new_tiles):
        for dx, dy in autoborder.NEIGHBOURS:
            q = (x + dx, y + dy)
            if q not in tiles and existing(*q) is not None and (q[0], q[1], Z) not in prefab_tiles:
                ring.add(q)
    reborder = 0
    for (x, y) in ring:
        t = existing(x, y)
        blobs = pvmap.split_items(t.children)
        ids = pvmap.child_item_ids(t.children)
        ground_blob = None
        if t.ground is not None:
            ground, rest = t.ground, list(zip(ids, blobs))
        elif ids:
            ground, ground_blob, rest = ids[0], blobs[0], list(zip(ids[1:], blobs[1:]))
        else:
            continue
        center = brushes.by_item.get(ground)
        if center is None:
            continue
        nb = [brush_at(x + dx, y + dy) for dx, dy in autoborder.NEIGHBOURS]
        old_border = [i for i, _ in rest if i in brushes.border_item_ids]
        optional = center is not mountain and mountain in nb
        border = brushes.borders_for(center, nb, optional=optional, void_borders=True)
        if sorted(border) == sorted(old_border):
            continue
        others = [blob for i, blob in rest if i not in brushes.border_item_ids]
        children = (ground_blob or b'') + b''.join(pvmap.item_node(i) for i in border) + b''.join(others)
        new_tiles[(x, y, Z)] = pvmap.RawTile(t.house_id, t.flags, t.ground, children)
        reborder += 1
    new_tiles.update(prefab_tiles)

    # The Elite Four building's west and south doors: take the counters out, keep the rest of the tile.
    for (x, y) in INDIGO_OPEN:
        t = existing(x, y)
        kept = [blob for i, blob in zip(pvmap.child_item_ids(t.children), pvmap.split_items(t.children))
                if i not in BALCONIES]
        new_tiles[(x, y, Z)] = pvmap.RawTile(t.house_id, t.flags, t.ground, b''.join(kept))

    # Spawns along the routes, drawn from the game's encounter rates.
    shore = dilate(terrain == WATER, 5)  # sea borders on the shore tiles block
    walk_ok = np.isin(terrain, [GRASS, LAWN, SAND]) & gen & ~blocked_spawn & ~clear & ~road & ~shore & ~f.disc(2718, 800, 50)
    walk_ok &= ~dilate(np.isin(terrain, [MOUNTAIN, SNOW_PEAK]), 5)
    route_of = np.where(upper, '28', np.where(X < 2700, '29', np.where(X < 2895, '27', '26')))
    spawns = []
    cand = np.argwhere(walk_ok & (rng.random((f.h, f.w)) < 1 / 210.0) & (X < 3049))
    for iy, ix in cand:
        spawns.append((pick(rng, spawn_table(str(route_of[iy, ix]))), ix + f.x0, iy + f.y0, Z))

    cave_tiles, cave_spawns, cave_npcs = build_cave(brushes, present, rng)
    new_tiles.update(cave_tiles)
    spawns += cave_spawns
    npcs += cave_npcs

    data = open(base, 'rb').read()
    town = (NEW_BARK['town_id'], NEW_BARK['name'], tx, ty, Z)
    cut = pvmap.write_map(data, out_path, new_tiles, remove=PASS_DROP, towns=[town])
    write_spawns(os.path.join(os.path.dirname(out_path), 'map-spawn.xml'), spawns, npcs)
    write_houses(os.path.join(os.path.dirname(out_path), 'map-house.xml'), new_houses)
    print('wrote %s: %d new or changed tiles (%d Kanto tiles replaced, %d re-bordered), %d spawns, %d houses'
          % (out_path, len(new_tiles), cut, reborder, len(spawns), len(new_houses)))
    return {'tiles': tiles, 'terrain': terrain}


def write_spawns(path, monsters, npcs):
    src = open(os.path.join(WORLD, 'map-spawn.xml'), encoding='latin-1').read()
    add = []
    for name, x, y, z in npcs:
        add.append('  <spawn centerx="%d" centery="%d" centerz="%d" radius="1">\n'
                   '    <npc name="%s" x="0" y="0" z="%d" spawntime="60" level="0"/>\n  </spawn>' % (x, y, z, name, z))
    for name, x, y, z in monsters:
        add.append('  <spawn centerx="%d" centery="%d" centerz="%d" radius="1">\n'
                   '    <monster name="%s" x="0" y="0" z="%d" spawntime="60" level="0"/>\n  </spawn>' % (x, y, z, name, z))
    i = src.rindex('</spawns>')
    with open(path, 'w', encoding='latin-1', newline='') as f:
        f.write(src[:i] + '\n'.join(add) + '\n' + src[i:])


def write_houses(path, houses):
    src = open(os.path.join(WORLD, 'map-house.xml'), encoding='latin-1').read()
    add = ['  <house name="%(name)s" houseid="%(houseid)d" entryx="%(entryx)d" entryy="%(entryy)d" entryz="%(entryz)d" '
           'rent="%(rent)d" townid="%(townid)d" size="%(size)d"/>' % h for h in houses]
    i = src.rindex('</houses>')
    with open(path, 'w', encoding='latin-1', newline='') as f:
        f.write(src[:i] + '\n'.join(add) + '\n' + src[i:])


