    east_scope = (X >= EAST[0]) & (X <= EAST[2]) & (Y >= EAST[1] + inset) & (Y <= EAST[3])
    for pl in places:
        cx, cy, r = pl['clear']
        west |= f.disc(cx, cy, r + 15, edge, 0.3) & (X >= GOLD[0])
    kanto_gaps = (X > JOHTO_X1) & (Y >= FAR_NORTH) & (Y < KANTO_GAPS_TO) & ~present
    rest = (X <= JOHTO_X1) | (Y < FAR_NORTH) | kanto_gaps
