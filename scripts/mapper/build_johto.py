    terrain[mount] = MOUNTAIN
    terrain[water] = WATER
    terrain[road & ~water] = DIRT
    terrain[snow_peak] = SNOW_PEAK
    frozen = (f.refine(coarse['snow'], n3, 0.5) & land & ~mount & ~water
              & (X > FROZEN[0] + n2 * 16) & (X < FROZEN[1] + f.noise(16) * 16) & (Y < FROZEN[2] + n1 * 12))
    # the snow thins out a few tiles short of the towns, on a ragged line (snow has no borders)
