def scan(path):
    """One pass over the base map, collecting what the layout and the builder need."""
    st = os.stat(path)
    cache = '/tmp/pv_scan_%d_%d_%s.pkl' % (st.st_size, int(st.st_mtime), '_'.join(map(str, BOX)))
    if os.path.exists(cache):
        return pickle.load(open(cache, 'rb'))
    data = open(path, 'rb').read()
    lx0, ly0, lx1, ly1 = L.LAYOUT_BOX
    ground7 = np.zeros((ly1 - ly0 + 1, lx1 - lx0 + 1), np.uint16)
    bx0, by0, bx1, by1 = BOX
    present = np.zeros((by1 - by0 + 3, bx1 - bx0 + 3), bool)
    occupied = set()
    keep = {}
    keep_boxes = [((bx0 - 1, by0 - 1, bx1 + 1, by1 + 1), (Z,))]
    for p in PREFABS.values():
        x0, y0, x1, y1 = p['box']
        keep_boxes.append(((x0, y0, x1, y1), range(0, p['z'] + 1)))
    area = None
    cur = None
    pending = None
    for ev, t, depth, a, b, _ in pvmap.walk(data):
        if ev == 'open':
            if t == pvmap.TILE_AREA:
                area = struct.unpack_from('<HHB', pvmap.unescape(data[a:b]), 0)
            elif t in (pvmap.TILE, pvmap.HOUSETILE):
                p = pvmap.unescape(data[a:b])
                x, y, z = area[0] + p[0], area[1] + p[1], area[2]
                occupied.add((x >> 5, y >> 5))
                if bx0 - 1 <= x <= bx1 + 1 and by0 - 1 <= y <= by1 + 1:
                    present[y - by0 + 1, x - bx0 + 1] = True
                _, _, house_id, flags, item = pvmap.parse_tile_props(p, t == pvmap.HOUSETILE)
                pending = None
                if z == Z and lx0 <= x <= lx1 and ly0 <= y <= ly1:
                    if item is not None:
                        ground7[y - ly0, x - lx0] = item
                    else:
                        pending = (x, y)
                cur = None
                for (x0, y0, x1, y1), floors in keep_boxes:
                    if x0 <= x <= x1 and y0 <= y <= y1 and z in floors:
                        cur = pvmap.RawTile(house_id, flags, item, b)
                        keep[(x, y, z)] = cur
                        break
            elif t == pvmap.ITEM and depth == 4 and pending is not None:
                ground7[pending[1] - ly0, pending[0] - lx0] = struct.unpack_from('<H', pvmap.unescape(data[a:a + 4]), 0)[0]
                pending = None
        elif t in (pvmap.TILE, pvmap.HOUSETILE):
            if cur is not None:
                cur.children = data[cur.children:b - 1]
            cur = None
            pending = None
    out = {'ground7': ground7, 'present': present, 'occupied': occupied, 'keep': keep}
    pickle.dump(out, open(cache, 'wb'))
    return out


def ground_class(ground7, brushes):
    lx0, ly0 = L.LAYOUT_BOX[:2]

    def cls(x, y):
        g = int(ground7[y - ly0, x - lx0])
        if g == 0:
            return L.VOID
        if g in WATER_IDS:
            return L.WATER
        brush = brushes.by_item.get(g)
        if brush is None:
            return L.OTHER
        return {'mountain': L.MOUNTAIN, 'grass': L.GRASS, 'sand': L.SAND}.get(brush.name, L.OTHER)
    return cls


