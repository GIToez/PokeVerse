class Prefab:
    """A Kanto building copied by its box. Plain prefabs have their door below the box (`door` is its
    first column); walled ones include the walls and get their entries from map-house.xml, and only
    keep the houses whose entry is in the box (a neighbour's tile on a shared wall is not theirs).
    Landmarks (rent False) are not houses at all; `entries` overrides where the doors are."""

    def __init__(self, name, spec, keep, brushes, nature, houses_xml, down_ids=()):
        self.name = name
        x0, y0, x1, y1 = spec['box']
        self.w, self.h = x1 - x0 + 1, y1 - y0 + 1
        self.base_z = spec['z']
        self.tiles = {}
        self.house_ids = set()
        self.src = (x0, y0)
        self.door = spec.get('door', self.w // 2 - 1)
        if spec.get('walled'):
            own = {hid for hid, h in houses_xml.items()
                   if x0 <= int(h['entryx']) <= x1 and y0 <= int(h['entryy']) <= y1 and int(h['entryz']) == self.base_z}
            self.entries = sorted({(int(houses_xml[hid]['entryx']) - x0, int(houses_xml[hid]['entryy']) - y0)
                                   for hid in own})
        else:
            own = None
            self.entries = [(self.door, self.h), (self.door + 1, self.h)]
        self.entries = spec.get('entries', self.entries)
        if not spec.get('rent', True):
            own = set()
        # the base floor's plain nature is left out, for the ground round the building to fill;
        # with `enclosed`, only what joins the box's edge (a pool or rockery indoors stays)
        loose = set()
        for (x, y, z), tile in keep.items():
            if z == self.base_z and x0 <= x <= x1 and y0 <= y <= y1 and not tile.house_id:
                ids = ([tile.ground] if tile.ground is not None else []) + pvmap.child_item_ids(tile.children)
                if all(i in nature for i in ids):
                    loose.add((x - x0, y - y0))
        if spec.get('enclosed'):
            todo = [(dx, dy) for dx, dy in loose if dx in (0, self.w - 1) or dy in (0, self.h - 1)]
            outside = set(todo)
            while todo:
                dx, dy = todo.pop()
                for p in ((dx + 1, dy), (dx - 1, dy), (dx, dy + 1), (dx, dy - 1)):
                    if p in loose and p not in outside:
                        outside.add(p)
                        todo.append(p)
            loose = outside
        for (x, y, z), tile in keep.items():
            if z > self.base_z or (spec.get('flat') and z < self.base_z):
                continue
            ux0, uy0, ux1, uy1 = upper_box(spec['box'], self.base_z - z)
            if not (ux0 <= x <= ux1 and uy0 <= y <= uy1):
                continue
            if own is not None and tile.house_id and tile.house_id not in own:
                tile = pvmap.RawTile(0, tile.flags, tile.ground, tile.children)
            if z == self.base_z and (x - x0, y - y0) in loose:
                continue
            if tile.house_id:
                self.house_ids.add(tile.house_id)
            self.tiles[(x - x0, y - y0, z - self.base_z)] = tile
        # an upper floor's box takes in a strip of the neighbour's roofs, and the stairs down in it
        # would lead nowhere
        for (dx, dy, dz), tile in list(self.tiles.items()):
            ids = ([tile.ground] if tile.ground is not None else []) + pvmap.child_item_ids(tile.children)
            if dz < 0 and (dx, dy, dz + 1) not in self.tiles and any(i in down_ids for i in ids):
                del self.tiles[(dx, dy, dz)]
        # doorways knocked through a wall (`open`): only the floor under it is kept
        for dx, dy in spec.get('open', []):
            tile = self.tiles[(dx, dy, 0)]
            floor = b'' if tile.ground is not None else pvmap.split_items(tile.children)[0]
            self.tiles[(dx, dy, 0)] = pvmap.RawTile(tile.house_id, tile.flags, tile.ground, floor)
        # things in pieces (a bench, a big rock) that the box's edge cuts go: half of one looks broken
        for (dx, dy, dz), tile in list(self.tiles.items()):
            blobs = pvmap.split_items(tile.children)
            kept = [b for b in blobs if not broken_piece(self.tiles, (dx, dy, dz), pvmap.child_item_ids(b)[0])]
            if len(kept) < len(blobs):
                self.tiles[(dx, dy, dz)] = pvmap.RawTile(tile.house_id, tile.flags, tile.ground, b''.join(kept))
        # a strip of the Pokémon Center next door in Kanto goes, with its lamps and the invisible walls
        # at its corners (on the box's edge; the Mart has its own), Kanto's signs to its towns and
        # routes ("Fuchsia to the East"), and tiles left empty
        if name != 'pokecenter':
            for (dx, dy, dz), tile in list(self.tiles.items()):
                blobs = pvmap.split_items(tile.children)
                firsts = [pvmap.child_item_ids(b)[0] for b in blobs]
                drop = set(KANTO_SIGNS)
                if tile.ground in PC_PIECES or PC_PIECES & set(firsts):
                    drop |= PC_PIECES | {PC_LAMP, FLY_BARRIER}
                elif dz == 0 and name != 'mart' and (dx in (0, self.w - 1) or dy in (0, self.h - 1)):
                    drop.add(FLY_BARRIER)
                kept = [b for b, i in zip(blobs, firsts) if i not in drop]
                if tile.ground in PC_PIECES or (tile.ground is None and not kept):
                    del self.tiles[(dx, dy, dz)]
                elif len(kept) < len(blobs):
                    self.tiles[(dx, dy, dz)] = pvmap.RawTile(tile.house_id, tile.flags, tile.ground, b''.join(kept))
        self.npcs = [(n, x - x0, y - y0) for n, x, y in spec.get('npcs', [])]
        self.footprint = {(dx, dy) for (dx, dy, dz) in self.tiles if dz == 0}


def broken_piece(tiles, pos, sid):
    """Whether item sid at pos is a piece of a thing in PIECES with another piece missing."""
    if sid not in PIECE_OF:
        return False
    shape, (ox, oy) = PIECE_OF[sid]
    x, y, z = pos
    for (px, py), other in shape.items():
        t = tiles.get((x - ox + px, y - oy + py, z))
        if t is None or other not in pvmap.child_item_ids(t.children):
            return True
    return False


def floor_down_ids(way='down'):
    """Items that take players down a floor when they step on them (items.xml floorchange down), or
    with way '[a-z]+' any floor change."""
    xml = open(os.path.join(ROOT, 'core/server/data/items/items.xml'), encoding='latin-1').read()
    out = set()
    for m in re.finditer(r'<item\s+(?:id="(\d+)"|fromid="(\d+)"\s+toid="(\d+)")[^>]*?(?:/>|>(.*?)</item>)', xml, re.S):
        if m.group(4) and re.search(r'key="floorchange" value="%s"' % way, m.group(4)):
            a = int(m.group(1) or m.group(2))
            out |= set(range(a, int(m.group(1) or m.group(3)) + 1))
    return out


def restyled(tile, swap):
    """The tile with its item ids swapped by `swap` (an id mapped to None is taken out)."""
    ground = swap.get(tile.ground, tile.ground) if tile.ground is not None else None
    children = b''
    for blob in pvmap.split_items(tile.children):
        sid = pvmap.child_item_ids(blob)[0]
        if sid in swap:
            if swap[sid] is None:
                continue
            assert sum(1 for ev in pvmap.walk(blob, 0) if ev[0] == 'open') == 1, 'item %d holds items' % sid
            props = pvmap.unescape(blob[2:-1])
            blob = bytes([pvmap.START, pvmap.ITEM]) + pvmap.escape(struct.pack('<H', swap[sid]) + props[2:]) + bytes([pvmap.END])
        children += blob
    return pvmap.RawTile(tile.house_id, tile.flags, ground, children)


def gym_puzzles(places, prefab_tiles, npcs, gym):
    """Redraws the gyms in GYM_PLANS over their placed shells (gym: the shell's Prefab) and adds
    their trainers; returns the positions left open as drops."""
    drops = []
    for place in places:
        plan = GYM_PLANS.get(place['name'])
        if plan is None:
            continue
        (ox, oy), = [(x, y) for name, x, y in place['buildings'] if name == 'gym']
        cracked, lifts = [], []
        for z, rows in plan['floors'].items():
            for dy, row in enumerate(rows):
                for dx, ch in enumerate(row):
                    pos = (ox + 1 + dx, oy + 1 + dy, z)
                    shell = prefab_tiles.get(pos)
                    if shell is None and ch == '_':
                        # the shell's planters are the ground round the building showing through
                        shell = next(prefab_tiles[p] for p in ((pos[0] + 1, pos[1], z), (pos[0] - 1, pos[1], z),
                                                               (pos[0], pos[1] + 1, z), (pos[0], pos[1] - 1, z))
                                     if p in prefab_tiles)
                    assert shell is not None, '%s gym plan runs outside the building at %s' % (place['name'], pos)
                    if ch == '.':
                        continue
                    if ch == ' ':
                        del prefab_tiles[pos]
                        drops.append(pos)
                        continue
                    if ch == '_':
                        ground, items = GYM_FLOOR, b''
                    elif ch == '=':
                        ground, items = GYM_PLANKS[zlib.crc32(repr(pos).encode()) % len(GYM_PLANKS)], b''
                    elif ch == 'x':
                        ground, items = None, pvmap.item_node(GYM_CRACKED, GYM_CRACKED_AID)
                        cracked.append(pos)
                    elif ch in '^v':
                        ground, items = GYM_FLOOR, pvmap.item_node(GYM_UP if ch == '^' else GYM_DOWN)
                    elif ch == 'g':
                        ground, items = GYM_GLASS, b''
                    elif ch in 'UD':
                        ground, items = None, pvmap.item_node(GYM_LIFT, GYM_LIFT_UP_AID if ch == 'U' else GYM_LIFT_DOWN_AID)
                        lifts.append((pos, (pos[0], pos[1] - 1, z - 1) if ch == 'U' else (pos[0], pos[1] + 1, z + 1)))
                    else:
                        raise ValueError('%s gym plan: unknown tile %r' % (place['name'], ch))
                    prefab_tiles[pos] = pvmap.RawTile(shell.house_id, shell.flags, ground, items)
        swap = plan.get('restyle')
        if swap:
            drawn = {(ox + 1 + dx, oy + 1 + dy, z) for z, rows in plan['floors'].items()
                     for dy, row in enumerate(rows) for dx in range(len(row))}
            for pos in drawn | {(ox + dx, oy + dy, Z + dz) for dx, dy, dz in gym.tiles}:
                if pos in prefab_tiles:
                    prefab_tiles[pos] = restyled(prefab_tiles[pos], swap)
        # a cracked plank drops players to the first floor below with ground under them
        for x, y, z in cracked:
            assert any((x, y, zz) in prefab_tiles for zz in range(z + 1, Z + 1)), \
                '%s gym: nothing under the cracked plank at %s' % (place['name'], (x, y, z))
        for pos, to in lifts:
            assert to in prefab_tiles, '%s gym: the lift at %s goes nowhere' % (place['name'], pos)
        for name, dx, dy, z in plan['npcs']:
            assert (ox + dx, oy + dy, z) in prefab_tiles, '%s gym: %s stands over a drop' % (place['name'], name)
            npcs.append((name, ox + dx, oy + dy, z))
    return drops


def joined(start, cells):
    """The cells joined to start (diagonals count)."""
    taken, queue = {start}, collections.deque([start])
    while queue:
        x, y = queue.popleft()
        for dx in (-1, 0, 1):
            for dy in (-1, 0, 1):
                n = (x + dx, y + dy)
                if n in cells and n not in taken:
                    taken.add(n)
                    queue.append(n)
    return taken


def underground_tiles(data, brushes):
    """The UNDERGROUND pieces' tiles, keyed by where they go, without house ids."""
    boxes = [box for piece in UNDERGROUND for box, _, _ in piece['floors'].values()]
    floors = {z for piece in UNDERGROUND for z in piece['floors']}
    raw = pvmap.read_region_raw(None, min(b[0] for b in boxes), min(b[1] for b in boxes),
                                max(b[2] for b in boxes), max(b[3] for b in boxes), floors, data)
    rock = {i for i, _ in brushes['mountain'].items}
    out = {}
    for piece in UNDERGROUND:
        before = len(out)
        ox, oy = piece['dst'][0] - piece['src'][0], piece['dst'][1] - piece['src'][1]
        for z, ((x0, y0, x1, y1), seed, neighbour) in piece['floors'].items():
            inside = {(x, y) for (x, y, zz) in raw if zz == z and x0 <= x <= x1 and y0 <= y <= y1}
            if neighbour is not None:
                def ground(p):
                    t = raw[(*p, z)]
                    return t.ground if t.ground is not None else (pvmap.child_item_ids(t.children) or [None])[0]
                inside -= joined(neighbour, {p for p in inside if ground(p) not in rock})
            if seed is not None:
                inside = joined(seed, inside)
            for x, y in inside:
                t = raw[(x, y, z)]
                assert (x + ox, y + oy, z) not in out, '%s overlaps another piece' % piece['name']
                out[(x + ox, y + oy, z)] = pvmap.RawTile(0, t.flags, t.ground, t.children)
        xs, ys, zs = zip(*list(out)[before:])
        piece['extent'] = (min(xs), min(ys), min(zs), max(xs), max(ys), max(zs))
        print('%s: %d tiles on floors %s' % (piece['name'], len(out) - before, sorted(piece['floors'])))
    return out


