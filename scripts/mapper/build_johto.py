    for k in range(1, 12):
        grown = dilate(near, 3)
        town_d[grown & ~near] = k
        near = grown
    town_d[~near] = 99
    frozen &= town_d + f.noise(7) * 8 > 5
    terrain[frozen & ~road] = SNOW
    clear = np.zeros((f.h, f.w), bool)

    bridge = {}

