    terrain[town_water] = WATER
    terrain[islets & ~land] = MOUNTAIN
    for (x, y), b in town_ground.items():
        terrain[y - f.y0, x - f.x0] = WATER if b == 'walkable sea' else PAVE
    streets = np.any(list(town_pave.values()), axis=0)
