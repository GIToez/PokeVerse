    # Mountain wall between Route 26 and Route 28, joining Kanto's ridge west of the plateau.
    ridge_line = [(2800, 655), (2870, 645), (2940, 652), (3000, 640), (3049, 628)]
    ridge = ((f.seg_dist(ridge_line) + n2 * 14 < 16) & (X > 2780) & (X < 3050)) | (upper & ~valley)
    land |= ridge & (X > 2790)
    land |= valley
    water &= ~upper
    water |= pond
    forest &= ~upper
    mount |= ridge & land
    mount &= ~valley
    snow_peak = f.disc(2905, 395, 72, n3, 0.6) & erode(mount & upper, 9)
    summits = np.zeros((f.h, f.w), bool)
    for x, y, r in SNOW_PEAKS:
        summits |= f.disc(x, y, r, n3, 0.5) & erode(mount, 7)
