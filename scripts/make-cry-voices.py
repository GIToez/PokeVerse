#!/usr/bin/env python3
"""Writes the client's voice line -> cry table (game_sounds/cry_voices.lua).

Every monster in core/server/data/monster/monsters.xml with <voice sentence="..."/> lines gives
its dex number (from the server's config/pokemonsNumbers.lua). When a Pokemon says one of
those lines the client plays /sounds/cries/<number>.ogg. Summons can have nicknames, so the
line itself is the key; a line used by more than one species is false and the client falls
back to the speaker's name (CryNames).

Usage: make-cry-voices.py
"""
import os
import re
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MONSTERS = os.path.join(ROOT, "core/server/data/monster")
NUMBERS = os.path.join(ROOT, "core/server/data/lib/ps/config/pokemonsNumbers.lua")
CRIES = os.path.join(ROOT, "core/client-redemption/data/sounds/cries")
OUTPUT = os.path.join(ROOT, "core/client-redemption/pokeverse-modern/modules/game_sounds/cry_voices.lua")


def lua_string(text):
    return '"%s"' % text.replace("\\", "\\\\").replace('"', '\\"')


def load_numbers():
    with open(NUMBERS, encoding="utf-8", errors="replace") as f:
        source = f.read()
    start = source.index("local pokemonsNumbers")
    end = source.index("}", start)
    numbers = {}
    for line in source[start:end].splitlines():
        match = re.match(r'\s*\["([^"]+)"\]\s*=\s*(\d+)', line)
        if match:
            numbers[match.group(1).lower()] = int(match.group(2))
    return numbers


def number_for(name, numbers):
    words = name.lower().split()
    # "Shiny Pikachu", "Christmas Pikachu", "Boss Shiny Pikachu" -> the longest known tail
    for i in range(len(words)):
        tail = " ".join(words[i:])
        if tail in numbers:
            return numbers[tail]
    return None


def main():
    numbers = load_numbers()
    cries = {int(f[:-4]) for f in os.listdir(CRIES) if re.match(r"^\d+\.ogg$", f)}
    voices = {}
    for entry in ET.parse(os.path.join(MONSTERS, "monsters.xml")).getroot().iter("monster"):
        number = number_for(entry.get("name", ""), numbers)
        path = os.path.join(MONSTERS, entry.get("file", ""))
        if number not in cries or not os.path.isfile(path):
            continue
        with open(path, encoding="utf-8", errors="replace") as f:
            sentences = re.findall(r'<voice\s+sentence="([^"]+)"', f.read())
        for sentence in sentences:
            voices.setdefault(sentence, set()).add(number)

    names = {name: n for name, n in numbers.items() if n in cries}
    lines = ["-- Generated by scripts/make-cry-voices.py from the server's monsters: voice line -> dex number",
             "-- (false: several species say it), and species name (lower case) -> dex number.",
             "CryVoices = {"]
    for sentence in sorted(voices):
        found = voices[sentence]
        lines.append("    [%s] = %s," % (lua_string(sentence), found.pop() if len(found) == 1 else "false"))
    lines += ["}", "", "CryNames = {"]
    for name in sorted(names):
        lines.append("    [%s] = %d," % (lua_string(name), names[name]))
    lines.append("}")
    with open(OUTPUT, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("%d voice lines, %d names -> %s" % (len(voices), len(names), os.path.relpath(OUTPUT, ROOT)))


if __name__ == "__main__":
    main()
