#!/usr/bin/env python3
"""Writes the client's lists of shiny and Mega Pokemon outfits (game_creaturefx/shiny_looks.lua and
mega_looks.lua).

Every monster in core/server/data/monster/monsters.xml named "Shiny ..." gives its look type to the
shiny list, and every "Mega ...", "Shiny Mega ..." and "Primal ..." to the Mega list. The client can't
tell a shiny from its name (wild shinies use the plain species name as their nickname), and a Mega keeps
its nickname, but both have their own sprites, so the look type is enough.

Usage: make-shiny-looks.py
"""
import os
import re
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MONSTERS = os.path.join(ROOT, "core/server/data/monster")
FX = os.path.join(ROOT, "core/client-redemption/pokeverse-modern/modules/game_creaturefx")
LISTS = [
    ("shiny_looks.lua", "ShinyLooks", "the look types of shiny Pokemon", lambda name: name.startswith("shiny ")),
    ("mega_looks.lua", "MegaLooks", "the look types of Mega and Primal forms",
     lambda name: re.match(r"^(shiny )?(mega|primal) ", name) is not None),
]


def look_types(wanted):
    looks = set()
    for entry in ET.parse(os.path.join(MONSTERS, "monsters.xml")).getroot().iter("monster"):
        if not wanted(entry.get("name", "").lower()):
            continue
        with open(os.path.join(MONSTERS, entry.get("file")), encoding="utf-8", errors="replace") as f:
            match = re.search(r'<look\s+type="(\d+)"', f.read())
        if match:
            looks.add(int(match.group(1)))
    return looks


def write(filename, table, what, looks):
    lines = ["-- Generated by scripts/make-shiny-looks.py from the server's monsters: %s." % what,
             "%s = {" % table]
    row = []
    for look in sorted(looks):
        row.append("[%d] = true" % look)
        if len(row) == 10:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append("}")
    output = os.path.join(FX, filename)
    os.makedirs(os.path.dirname(output), exist_ok=True)
    with open(output, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("%d looks -> %s" % (len(looks), os.path.relpath(output, ROOT)))


def main():
    for filename, table, what, wanted in LISTS:
        write(filename, table, what, look_types(wanted))


if __name__ == "__main__":
    main()
