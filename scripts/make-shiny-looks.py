#!/usr/bin/env python3
"""Writes the client's list of shiny Pokemon outfits (game_creaturefx/shiny_looks.lua).

Every monster in core/server/data/monster/monsters.xml named "Shiny ..." gives its look type.
The client can't tell a shiny from its name (wild shinies use the plain species name as their
nickname), but shinies have their own sprites, so the look type is enough.

Usage: make-shiny-looks.py
"""
import os
import re
import xml.etree.ElementTree as ET

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MONSTERS = os.path.join(ROOT, "core/server/data/monster")
OUTPUT = os.path.join(ROOT, "core/client-redemption/pokeverse-modern/modules/game_creaturefx/shiny_looks.lua")


def main():
    looks = set()
    for entry in ET.parse(os.path.join(MONSTERS, "monsters.xml")).getroot().iter("monster"):
        if not entry.get("name", "").lower().startswith("shiny "):
            continue
        with open(os.path.join(MONSTERS, entry.get("file")), encoding="utf-8", errors="replace") as f:
            match = re.search(r'<look\s+type="(\d+)"', f.read())
        if match:
            looks.add(int(match.group(1)))

    lines = ["-- Generated by scripts/make-shiny-looks.py from the server's monsters: the look types of shiny Pokemon.",
             "ShinyLooks = {"]
    row = []
    for look in sorted(looks):
        row.append("[%d] = true" % look)
        if len(row) == 10:
            lines.append("    " + ", ".join(row) + ",")
            row = []
    if row:
        lines.append("    " + ", ".join(row) + ",")
    lines.append("}")
    os.makedirs(os.path.dirname(OUTPUT), exist_ok=True)
    with open(OUTPUT, "w", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("%d shiny looks -> %s" % (len(looks), os.path.relpath(OUTPUT, ROOT)))


if __name__ == "__main__":
    main()
