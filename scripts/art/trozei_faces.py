#!/usr/bin/env python3
"""Swap bar and Pokédex faces from the Pokémon Battle Trozei "Small Pokémon Icons" sheet.

    scripts/art/trozei_faces.py <sheet.png> [--preview out.png]

The sheet (spriters-resource.com, 3DS > Pokémon Battle Trozei, asset 64891) is 24 x 32 cells of
64x64: a Poké Ball, then #1 to #718 in order with some forms in between. Each face is shrunk to
32x32 and written to core/client-legacy/data/images/faces/<dex>/0.png. Shiny Pokémon get the
face recoloured with the colours of our old shiny face (old normal face -> old shiny face).

things.otml then points every face item at those images: the swap bar face (fastcallPortrait),
the inventory portrait (portrait, through items.otb) and the Pokédex grid face of each Pokémon
we have. Faces past #386 are written for when those Pokémon are added.
"""
import argparse
import glob
import json
import os
import re
import sys

import numpy as np
from PIL import Image, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, 'scripts', 'art'))
sys.path.insert(0, os.path.join(ROOT, 'scripts'))
from new_pokemon_art_preview import Things  # noqa: E402

CONFIG = os.path.join(ROOT, 'core', 'server', 'data', 'lib', 'ps', 'config')
ITEMS_OTB = os.path.join(ROOT, 'core', 'server', 'data', 'items', 'items.otb')
IMAGES = os.path.join(ROOT, 'core', 'client-legacy', 'data', 'images')
THINGS_OTML = os.path.join(ROOT, 'core', 'client-legacy', 'data', 'things', 'things.otml')
FACES = '/images/faces'
LAST_DEX = 718
# cells that are not the next Pokédex number: the second Jigglypuff, Unown B to ?, East Sea
# Shellos and Gastrodon, Sky Shaymin, blue Basculin, Zen Darmanitan, female Frillish and
# Jellicent, White and Black Kyurem, Resolute Keldeo, two more Pyroar and female Meowstic
EXTRA_CELLS = {40, *range(203, 230), 451, 453, 523, 582, 588, 626, 628, 682, 683, 685, 707, 708, 719}
BEGIN = '  # trozei faces: generated by scripts/art/trozei_faces.py'
END = '  # end of trozei faces'


def dex_cells():
    cells = [c for c in range(1, 24 * 32) if c not in EXTRA_CELLS]
    return {dex: cells[dex - 1] for dex in range(1, LAST_DEX + 1)}


def cell_image(sheet, cell):
    row, col = divmod(cell, 24)
    return sheet.crop((col * 64, row * 64, col * 64 + 64, row * 64 + 64))


def to_face(img):
    """64x64 RGBA to 32x32 with hard alpha (the item renderer has no partial transparency)."""
    a = np.asarray(img.convert('RGBA')).astype(np.float64) / 255
    rgb, alpha = a[..., :3], a[..., 3:]
    pre = (rgb * alpha).reshape(32, 2, 32, 2, 3).mean(axis=(1, 3))
    al = alpha.reshape(32, 2, 32, 2, 1).mean(axis=(1, 3))
    rgb = np.where(al > 0, pre / np.maximum(al, 1e-6), 0)
    out = np.concatenate([rgb, (al > 0.45).astype(np.float64)], axis=2)
    return Image.fromarray((out * 255).round().astype(np.uint8), 'RGBA')


def colour_map(normal, shiny, k=10):
    """Old normal face -> old shiny face as k colour groups of the normal face and their shiny colour."""
    n = np.asarray(normal.convert('RGBA')).reshape(-1, 4).astype(np.float64)
    s = np.asarray(shiny.convert('RGBA')).reshape(-1, 4).astype(np.float64)
    keep = (n[:, 3] > 127) & (s[:, 3] > 127)
    if keep.sum() < 20:
        return None
    n, s = n[keep, :3], s[keep, :3]
    rng = np.random.default_rng(0)
    centres = n[rng.choice(len(n), min(k, len(n)), replace=False)]
    for _ in range(20):
        group = np.argmin(((n[:, None] - centres[None]) ** 2).sum(-1), axis=1)
        centres = np.array([n[group == g].mean(0) if (group == g).any() else centres[g] for g in range(len(centres))])
    group = np.argmin(((n[:, None] - centres[None]) ** 2).sum(-1), axis=1)
    targets = np.array([s[group == g].mean(0) if (group == g).any() else centres[g] for g in range(len(centres))])
    return centres, targets


def luma(rgb):
    return rgb @ np.array([0.299, 0.587, 0.114])


def recolour(face, table):
    """Each pixel takes the shiny colour of its nearest normal colour, keeping its own light and shade."""
    centres, targets = table
    a = np.asarray(face).astype(np.float64)
    rgb = a[..., :3].reshape(-1, 3)
    group = np.argmin(((rgb[:, None] - centres[None]) ** 2).sum(-1), axis=1)
    out = targets[group] + (luma(rgb) - luma(centres[group]))[:, None]
    a[..., :3] = np.clip(out, 0, 255).reshape(32, 32, 3)
    return Image.fromarray(a.round().astype(np.uint8), 'RGBA')


def species():
    """{name: [fastcallPortrait, portrait]} for every Pokémon config the server loads."""
    out = {}
    for path in glob.glob(os.path.join(CONFIG, 'pokemon', '*.lua')):
        text = open(path, encoding='latin-1').read()
        for name, body in re.findall(r'POKEMON\["([^"]+)"\]\s*=\s*\{(.*?)\n\}', text, re.S):
            fast = re.search(r'fastcallPortrait\s*=\s*(-?\d+)', body)
            portrait = re.search(r'\bportrait\s*=\s*(-?\d+)', body)
            out[name] = [int(fast[1]) if fast else 0, int(portrait[1]) if portrait else 0]
        for name, key, value in re.findall(r'POKEMONS?\["([^"]+)"\]\.(fastcallPortrait|portrait)\s*=\s*(\d+)', text):
            out.setdefault(name, [0, 0])[key == 'portrait'] = int(value)
    text = open(os.path.join(CONFIG, 'pokemon.lua'), encoding='latin-1').read()
    for name, key, value in re.findall(r'POKEMONS?\["([^"]+)"\]\.(fastcallPortrait|portrait)\s*=\s*(\d+)', text):
        out.setdefault(name, [0, 0])[key == 'portrait'] = int(value)
    return out


def numbers():
    """{name: dex} for the plain Pokémon (the first name of each number; the others are costumes)."""
    text = open(os.path.join(CONFIG, 'pokemonsNumbers.lua'), encoding='latin-1').read()
    first = {}
    for name, n in re.findall(r'\["([^"]+)"\]\s*=\s*(\d+)', text):
        first.setdefault(int(n), name)
    return {name: n for n, name in first.items()}


def server_to_client():
    import importlib.util
    spec = importlib.util.spec_from_file_location('item_hooks', os.path.join(ROOT, 'scripts', 'item-hooks.py'))
    hooks = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(hooks)
    items = hooks.otb_items(open(ITEMS_OTB, 'rb').read())
    return {sid: hooks.client_id(item[4]) for sid, item in items.items()
            if any(a == hooks.otb.ATTR_CLIENTID for a, _ in item[4])}


def dex_grid_item(dex):
    if dex <= 151:
        return 11873 + dex
    if dex <= 251:
        return 15798 - 151 + dex
    return 27108 - 251 + dex


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('sheet')
    ap.add_argument('--preview')
    args = ap.parse_args()
    sheet = Image.open(args.sheet).convert('RGBA')
    faces = {dex: to_face(cell_image(sheet, cell)) for dex, cell in dex_cells().items()}

    things = Things()
    s2c = server_to_client()
    dex_of = numbers()
    configs = species()

    def old_face(client_id):
        return things.item_frames(client_id)[0] if client_id and client_id - 100 < len(things.items) else None

    entries = {}
    previews = []
    for dex, face in faces.items():
        os.makedirs(os.path.join(IMAGES, 'faces', str(dex)), exist_ok=True)
        face.save(os.path.join(IMAGES, 'faces', str(dex), '0.png'))
        if dex <= 386:
            entries[dex_grid_item(dex)] = '%s/%d' % (FACES, dex)
    for name, (fast, portrait) in sorted(configs.items()):
        shiny = name.startswith('Shiny ')
        dex = dex_of.get(name[6:] if shiny else name)
        if not dex or dex > LAST_DEX:
            continue
        portrait_client = s2c.get(portrait if portrait > 0 else 28149 + dex)
        folder = '%s/%d' % (FACES, dex)
        face = faces[dex]
        if shiny:
            plain = configs.get(name[6:], [0, 0])[0]
            table = colour_map(old_face(plain), old_face(fast)) if old_face(plain) and old_face(fast) else None
            if not table:
                continue
            face = recolour(face, table)
            folder = '%s/shiny/%d' % (FACES, dex)
            os.makedirs(os.path.join(IMAGES, folder.split('/images/')[1]), exist_ok=True)
            face.save(os.path.join(IMAGES, folder.split('/images/')[1], '0.png'))
        for cid in (fast, portrait_client):
            if cid and cid > 100:
                entries[cid] = folder
        if args.preview and fast:
            previews.append((name, old_face(fast), face))

    lines = [BEGIN]
    for cid in sorted(entries):
        lines += ['  %d:' % cid, '    image-frames: %s 1' % entries[cid]]
    lines.append(END)
    text = open(THINGS_OTML, encoding='utf-8').read()
    text = re.sub(r'\n%s\n.*?\n%s\n' % (re.escape(BEGIN), re.escape(END)), '\n', text, flags=re.S)
    taken = set(int(x) for x in re.findall(r'^  (\d+):', text.split('\nitems:\n', 1)[1], re.M))
    clash = taken & set(entries)
    if clash:
        sys.exit('things.otml already has entries for items %s' % sorted(clash)[:10])
    open(THINGS_OTML, 'w', encoding='utf-8').write(text.rstrip('\n') + '\n' + '\n'.join(lines) + '\n')
    print('%d faces, %d shiny faces, %d face items' % (len(faces), sum('/shiny/' in v for v in set(entries.values())),
                                                       len(entries)))

    if args.preview:
        z, cols, cw = 3, 12, 32 * 3 * 2 + 18
        rows = (len(previews) + cols - 1) // cols
        im = Image.new('RGBA', (cols * cw, rows * (32 * z + 18)), (32, 36, 48, 255))
        d = ImageDraw.Draw(im)
        for k, (name, old, new) in enumerate(previews):
            x, y = (k % cols) * cw, (k // cols) * (32 * z + 18)
            if old:
                im.alpha_composite(old.resize((32 * z, 32 * z), Image.NEAREST), (x + 4, y))
            im.alpha_composite(new.resize((32 * z, 32 * z), Image.NEAREST), (x + 8 + 32 * z, y))
            d.text((x + 4, y + 32 * z + 2), name[:24], fill=(230, 230, 230))
        im.save(args.preview)


if __name__ == '__main__':
    main()
