#!/usr/bin/env python3
"""Write the client's list of Poke Ball item ids (modules/gamelib/pokeverse/balls.lua).

Reads every ball in the server's data/lib/ps/config/balls.lua (empty, in use, holding a Pokemon,
fainted) and maps the server ids to client ids through data/items/items.otb. Run it again after
adding a ball type.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, 'scripts', 'mapper'))
from pvmap import Otb  # noqa: E402

BALLS_LUA = os.path.join(ROOT, 'core/server/data/lib/ps/config/balls.lua')
OTB = os.path.join(ROOT, 'core/server/data/items/items.otb')
OUT = os.path.join(ROOT, 'core/client-redemption/pokeverse-modern/modules/gamelib/pokeverse/balls.lua')


def ranges(ids):
    out = []
    for i in sorted(ids):
        if out and i == out[-1][1] + 1:
            out[-1][1] = i
        else:
            out.append([i, i])
    return out


def main():
    otb = Otb(OTB)
    src = open(BALLS_LUA, encoding='latin1').read()
    body = src[src.index('\nballs = {'):]
    ids = set()
    for _, ball in re.findall(r'\n    \["([^"]+)"\] = \{(.*?)\n    \}', body, re.S):
        for sid in re.findall(r'\b(?:empty|inUse|charged|discharged)\s*=\s*(\d+)', ball):
            cid = otb.client_id(int(sid))
            if cid:
                ids.add(cid)
    if not ids:
        sys.exit('no balls found in ' + BALLS_LUA)
    lines = ['    { %d, %d },' % (a, b) for a, b in ranges(ids)]
    with open(OUT, 'w') as f:
        f.write('-- Generated by scripts/gen-ball-ids.py from the server\'s balls.lua: the client ids of every\n'
                '-- Poke Ball (empty, in use, holding a Pokemon, fainted). Do not edit by hand.\n\n'
                'PokeBalls = {}\n\n'
                'local RANGES = {\n' + '\n'.join(lines) + '\n}\n\n'
                'local isBall = {}\n'
                'for _, range in ipairs(RANGES) do\n'
                '    for id = range[1], range[2] do\n'
                '        isBall[id] = true\n'
                '    end\n'
                'end\n\n'
                'function PokeBalls.isBall(clientId)\n'
                '    return isBall[clientId] == true\n'
                'end\n')
    print('wrote %s: %d ids in %d ranges' % (os.path.relpath(OUT, ROOT), len(ids), len(lines)))


if __name__ == '__main__':
    main()
