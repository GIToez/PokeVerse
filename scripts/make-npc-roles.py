#!/usr/bin/env python3
"""Writes the client's table of what each NPC does, for the icons over their name plates.

    scripts/make-npc-roles.py

It reads every NPC file in core/server/data/npc and writes
core/client-redemption/pokeverse-modern/modules/game_quests/npc_roles.lua. The roles come from the NPC's
script and modules: battle, shop, travel, bank, heal and daycare. Quest marks are per trainer and come
from the server instead. Run it again after adding or changing NPCs.
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NPC_DIR = ROOT / 'core/server/data/npc'
OUT = ROOT / 'core/client-redemption/pokeverse-modern/modules/game_quests/npc_roles.lua'

ORDER = ['battle', 'shop', 'travel', 'bank', 'heal', 'daycare']
SHOP_SCRIPTS = ('shop_', 'casinoMerchant', 'tm_remover', 'vitamin_reset', 'gameplayTutorial_shop')


def roles_of(text):
    script = (re.search(r'<npc [^>]*script="([^"]*)"', text) or [None, ''])[1]
    params = dict(re.findall(r'<parameter key="([^"]*)" value="([^"]*)"', text))
    roles = set()
    if script.startswith('npcbattle_') or script == 'battleNpc.lua':
        roles.add('battle')
    if params.get('module_shop') == '1' or script.startswith(SHOP_SCRIPTS):
        roles.add('shop')
    if params.get('module_travel') == '1' or script.startswith('travels'):
        roles.add('travel')
    if script.startswith('bank'):
        roles.add('bank')
    if script == 'nurse_joy.lua':
        roles.add('heal')
    if script.startswith('daycare'):
        roles.add('daycare')
    return [role for role in ORDER if role in roles]


def lua_string(text):
    return "'" + text.replace('\\', '\\\\').replace("'", "\\'") + "'"


def main():
    table = {}
    for path in sorted(NPC_DIR.glob('*.xml')):
        text = path.read_text(encoding='utf-8', errors='replace')
        name = re.search(r'<npc [^>]*name="([^"]*)"', text)
        roles = roles_of(text)
        if name and roles:
            table[name[1]] = sorted(set(table.get(name[1], [])) | set(roles), key=ORDER.index)
    lines = ['-- Generated by scripts/make-npc-roles.py from the server\'s NPC files: what each NPC does.',
             'NpcRoles = {']
    for name in sorted(table):
        lines.append('    [%s] = { %s },' % (lua_string(name), ', '.join(lua_string(r) for r in table[name])))
    lines.append('}')
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    counts = {role: sum(role in roles for roles in table.values()) for role in ORDER}
    print('%d NPCs: %s' % (len(table), ', '.join('%s %d' % item for item in counts.items())))


if __name__ == '__main__':
    main()
